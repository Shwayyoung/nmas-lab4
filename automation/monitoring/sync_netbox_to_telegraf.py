#!/usr/bin/env python3
"""Generate Telegraf monitoring config for ZTP cEOS devices from NetBox."""

import os
import sys
import tempfile
from pathlib import Path

import requests

NETBOX_URL = os.getenv("NETBOX_URL", "http://127.0.0.1:8000").rstrip("/")
NETBOX_TOKEN = os.getenv("NETBOX_TOKEN")

TARGET_DEVICES = ("R6", "R7", "R8", "S5")
OUTPUT = Path("/etc/telegraf/telegraf.d/ztp-netbox.conf")

if not NETBOX_TOKEN:
    print("[Telegraf-Sync] ERROR: NETBOX_TOKEN is not set", file=sys.stderr)
    sys.exit(1)

HEADERS = {
    "Authorization": f"Token {NETBOX_TOKEN}",
    "Accept": "application/json",
}


def api_get(path, **params):
    url = f"{NETBOX_URL}/api/{path.lstrip('/')}"
    response = requests.get(
        url,
        headers=HEADERS,
        params=params,
        timeout=15,
    )
    if not response.ok:
        raise RuntimeError(
            f"GET {url} -> {response.status_code}\n{response.text}"
        )
    return response.json()


def get_device(name):
    data = api_get("dcim/devices/", name=name)
    results = data.get("results", [])

    if len(results) != 1:
        raise RuntimeError(
            f"{name}: expected one NetBox device, got {len(results)}"
        )

    device = results[0]

    if device.get("status", {}).get("value") != "active":
        raise RuntimeError(f"{name}: device is not Active in NetBox")

    manufacturer = (
        device.get("device_type", {})
        .get("manufacturer", {})
        .get("name", "")
        .lower()
    )
    if "arista" not in manufacturer:
        raise RuntimeError(
            f"{name}: expected Arista device, got {manufacturer!r}"
        )

    primary4 = device.get("primary_ip4")
    if not primary4:
        raise RuntimeError(f"{name}: no Primary IPv4 in NetBox")

    mgmt_ip = primary4["address"].split("/", 1)[0]

    custom = device.get("custom_fields", {})
    username = custom.get("management_username")
    secret_ref = custom.get("secret_ref")

    if not username:
        raise RuntimeError(
            f"{name}: management_username is missing in NetBox"
        )
    if not secret_ref:
        raise RuntimeError(
            f"{name}: secret_ref is missing in NetBox"
        )

    return {
        "name": name,
        "lower": name.lower(),
        "mgmt_ip": mgmt_ip,
        "username": username,
        "secret_ref": secret_ref,
    }


def render(devices):
    lines = [
        "# ------------------------------------------------------------------",
        "# AUTO-GENERATED FROM NETBOX. DO NOT EDIT BY HAND.",
        "# Generated by automation/monitoring/sync_netbox_to_telegraf.py",
        "# ------------------------------------------------------------------",
        "",
        "# cEOS CPU via SNMP",
        "[[inputs.snmp]]",
        "  agents = [",
    ]

    for device in devices:
        lines.append(f'    "udp://{device["mgmt_ip"]}:161",')

    lines += [
        "  ]",
        "  version = 2",
        '  community = "${SNMP_COMMUNITY}"',
        '  interval = "10s"',
        '  agent_host_tag = "agent_host"',
        "",
        "  [[inputs.snmp.field]]",
        '    name = "device"',
        '    oid = "1.3.6.1.2.1.1.5.0"',
        "    is_tag = true",
        "",
        "  [[inputs.snmp.table]]",
        '    name = "snmp_cpu"',
        "",
        "    [[inputs.snmp.table.field]]",
        '      name = "cpu_load"',
        '      oid = "1.3.6.1.2.1.25.3.3.1.2"',
        "",
    ]

    for device in devices:
        name = device["lower"]
        lines += [
            f"# {device['name']} interface telemetry via gNMI",
            "[[inputs.gnmi]]",
            f'  addresses = ["{device["mgmt_ip"]}:6030"]',
            f'  username = "{device["username"]}"',
            f'  password = "${{{device["secret_ref"]}}}"',
            '  encoding = "json_ietf"',
            "  tls_enable = false",
            '  path_guessing_strategy = "subscription"',
            "  prefix_tag_key_with_path = true",
            "",
            "  [[inputs.gnmi.subscription]]",
            f'    name = "{name}_interface_state"',
            '    path = "/interfaces/interface/state/oper-status"',
            'subscription_mode = "sample"',
            'sample_interval = "10s"',
            "",
            "  [[inputs.gnmi.subscription]]",
            f'    name = "{name}_interface_in_octets"',
            '    path = "/interfaces/interface/state/counters/in-octets"',
            '    subscription_mode = "sample"',
            '    sample_interval = "10s"',
            "",
            "  [[inputs.gnmi.subscription]]",
            f'    name = "{name}_interface_out_octets"',
            '    path = "/interfaces/interface/state/counters/out-octets"',
            '    subscription_mode = "sample"',
            '    sample_interval = "10s"',
            "",
        ]

    return "\n".join(lines) + "\n"


def write_atomic(content):
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)

    fd, temp_name = tempfile.mkstemp(
        prefix="ztp-netbox.",
        suffix=".conf",
        dir=str(OUTPUT.parent),
    )

    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)

        os.chmod(temp_name, 0o644)

        if OUTPUT.exists():
            backup = OUTPUT.with_suffix(".conf.bak")
            backup.write_text(
                OUTPUT.read_text(encoding="utf-8"),
                encoding="utf-8",
            )

        os.replace(temp_name, OUTPUT)

    finally:
        if os.path.exists(temp_name):
            os.unlink(temp_name)


def main():
    devices = [get_device(name) for name in TARGET_DEVICES]

    print("[Telegraf-Sync] NetBox targets:")
    for d in devices:
        print(
            f"  {d['name']}: {d['mgmt_ip']} "
            f"user={d['username']} secret={d['secret_ref']}"
        )

    content = render(devices)
    write_atomic(content)

    print(f"[Telegraf-Sync] Wrote {OUTPUT}")
    print("[Telegraf-Sync] Generation completed successfully")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"[Telegraf-Sync] ERROR: {exc}", file=sys.stderr)
        sys.exit(1)
